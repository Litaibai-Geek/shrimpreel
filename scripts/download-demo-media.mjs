#!/usr/bin/env node
// Download licensed Pexels preview clips, create lightweight local homepage media,
// and prepare R2 reference videos for Kie Seedance 2.0 Mini.
// Requires Node 24+ and ffmpeg on PATH (or FFMPEG_PATH).

import { createWriteStream } from 'node:fs'
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { execFileSync } from 'node:child_process'
import { Readable } from 'node:stream'
import { pipeline } from 'node:stream/promises'

const root = process.cwd()
const ffmpeg = process.env.FFMPEG_PATH || 'ffmpeg'
const temp = await mkdtemp(join(tmpdir(), 'tinydeskai-demo-'))
const previewDir = join(root, 'public', 'demo')
const templateDir = join(root, 'seed', 'templates')

const sources = {
  band: {
    url: 'https://videos.pexels.com/video-files/8197864/8197864-hd_1080_1920_30fps.mp4',
    file: 'band-session-source.mp4',
    output: 'band-session.mp4',
    poster: 'band-session.jpg',
    seconds: 14,
    credit: 'Pexels · RDNE Stock project',
    label: 'Band performance',
  },
  singer: {
    url: 'https://videos.pexels.com/video-files/8042848/8042848-uhd_2160_4096_25fps.mp4',
    file: 'singer-close-up-source.mp4',
    output: 'singer-close-up.mp4',
    poster: 'singer-close-up.jpg',
    seconds: 8,
    credit: 'Pexels · ANTONI SHKRABA production',
    label: 'Vocal close-up',
  },
  sax: {
    url: 'https://videos.pexels.com/video-files/5657391/5657391-uhd_2160_4096_25fps.mp4',
    file: 'sax-solo-source.mp4',
    output: 'sax-solo.mp4',
    poster: 'sax-solo.jpg',
    seconds: 4,
    credit: 'Pexels · cottonbro studio',
    label: 'Saxophone solo',
  },
}

const referenceSource = {
  url: 'https://videos.pexels.com/video-files/9419269/9419269-uhd_2160_4096_25fps.mp4',
  file: 'reference-singer-source.mp4',
}

async function download(url, destination) {
  const response = await fetch(url, { headers: { 'User-Agent': 'TinyDeskAI-demo-media-setup/1.0' } })
  if (!response.ok || !response.body) {
    throw new Error(`Download failed (${response.status}) for ${url}`)
  }
  const contentType = response.headers.get('content-type') || ''
  if (!contentType.includes('video/')) {
    throw new Error(`Expected video content from ${url}, got ${contentType || 'unknown content type'}`)
  }
  await pipeline(Readable.fromWeb(response.body), createWriteStream(destination))
}

function runFfmpeg(args) {
  execFileSync(ffmpeg, ['-hide_banner', '-loglevel', 'error', '-y', ...args], {
    stdio: 'inherit',
    shell: process.platform === 'win32',
  })
}

function transcode(input, output, seconds, width, height, fps, crf) {
  runFfmpeg([
    '-i', input,
    '-t', String(seconds),
    '-map', '0:v:0',
    '-vf', `scale=${width}:${height}:force_original_aspect_ratio=increase,crop=${width}:${height},fps=${fps},setsar=1`,
    '-an',
    '-sn',
    '-dn',
    '-c:v', 'libx264',
    '-preset', 'veryfast',
    '-crf', String(crf),
    '-pix_fmt', 'yuv420p',
    '-movflags', '+faststart',
    output,
  ])
}

function makePoster(input, output) {
  runFfmpeg(['-ss', '1', '-i', input, '-map', '0:v:0', '-frames:v', '1', '-q:v', '3', output])
}

try {
  await mkdir(previewDir, { recursive: true })
  await mkdir(templateDir, { recursive: true })
  await mkdir(temp, { recursive: true })

  // Download and optimize the three homepage preview clips.
  for (const item of Object.values(sources)) {
    const input = join(temp, item.file)
    await download(item.url, input)
    transcode(input, join(previewDir, item.output), item.seconds, 540, 960, 24, 28)
    makePoster(input, join(previewDir, item.poster))
    process.stdout.write(`Prepared public/demo/${item.output}\n`)
  }

  // The legacy providers receive a source clip matching the selected output duration.
  // Kie receives a separate fixed 14-second reference video; 18 seconds remains for legacy queued jobs.
  const referenceInput = join(temp, referenceSource.file)
  await download(referenceSource.url, referenceInput)
  transcode(referenceInput, join(templateDir, 'tiny-desk-v1-6s.mp4'), 6, 720, 1280, 30, 25)
  transcode(referenceInput, join(templateDir, 'tiny-desk-v1-12s.mp4'), 12, 720, 1280, 30, 25)
  transcode(referenceInput, join(templateDir, 'tiny-desk-v1-15s.mp4'), 15, 720, 1280, 30, 25)
  transcode(referenceInput, join(templateDir, 'tiny-desk-v1-reference-14s.mp4'), 14, 720, 1280, 30, 25)
  transcode(referenceInput, join(templateDir, 'tiny-desk-v1-18s.mp4'), 18, 720, 1280, 30, 25)

  const localConfig = `// Generated by npm run media:download. Source credits: docs/media/pexels-demo-media-credits.md
export const demoMedia = {
  band: { label: 'Band performance', video: '/demo/band-session.mp4', poster: '/demo/band-session.jpg', credit: 'Pexels · RDNE Stock project' },
  singer: { label: 'Vocal close-up', video: '/demo/singer-close-up.mp4', poster: '/demo/singer-close-up.jpg', credit: 'Pexels · ANTONI SHKRABA production' },
  sax: { label: 'Saxophone solo', video: '/demo/sax-solo.mp4', poster: '/demo/sax-solo.jpg', credit: 'Pexels · cottonbro studio' },
} as const
`
  await writeFile(join(root, 'src', 'config', 'demo-media.ts'), localConfig, 'utf8')

  process.stdout.write('\nDemo videos are now local under public/demo/.\n')
  process.stdout.write('R2 templates are ready under seed/templates/.\n')
  process.stdout.write('Next: npm run seed:local (local R2), then upload both MP4s to the production R2 bucket.\n')
} catch (error) {
  process.stderr.write(`\nMedia preparation failed: ${error instanceof Error ? error.message : String(error)}\n`)
  process.stderr.write('Check network access and make sure FFmpeg is installed and available on PATH.\n')
  process.exitCode = 1
} finally {
  await rm(temp, { recursive: true, force: true })
}
